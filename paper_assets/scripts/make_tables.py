def table_ranks(summ: pd.DataFrame) -> None:
    """Average ranks with the Nemenyi outcome, per comparison family."""
    rows = []
    for fam, label in (("baseline", "Reinforcement learning baselines"),
                       ("ablation", "Ablated variants")):
        f = summ[summ.family == fam].sort_values("avg_rank")
        cd = f.nemenyi_cd.iloc[0]
        chi2 = f.friedman_chi2.iloc[0]
        p = f.friedman_p.iloc[0]
        rows.append(rf"\multicolumn{{4}}{{l}}{{\textit{{{label}}}: "
                    rf"$\chi^2={chi2:.1f}$, $p={fmt_p(p).replace('$<$', '<')}$, "
                    rf"CD $={cd:.3f}$}} \\")
        for _, r in f.iterrows():
            if r.method == OURS:
                rows.append(rf"\quad {TEX[r.method]} & \textbf{{{r.avg_rank:.2f}}} "
                            r"& --- & --- \\")
            else:
                mark = r"\checkmark" if r.separated else r"$\circ$"
                rows.append(f"\\quad {TEX[r.method]} & {r.avg_rank:.2f} & "
                            f"{r.gap_to_best:+.2f} & {mark} \\\\")
        rows.append(r"\addlinespace")
    body = (r"""\begin{tabular}{lrrc}
\toprule
Method & Avg. rank & $\Delta$ rank & Separated \\
\midrule
""" + "\n".join(rows[:-1]) + r"""
\bottomrule
\multicolumn{4}{l}{\footnotesize Friedman test with the Nemenyi post-hoc
 procedure over $N=135$ blocks, computed} \\
\multicolumn{4}{l}{\footnotesize separately within each family. Lower ranks are
 better. \checkmark: the gap to} \\
\multicolumn{4}{l}{\footnotesize HCMAGRL exceeds the critical difference;
 $\circ$: it does not.} \\
\end{tabular}""")
    write(TABLES / "ranks.tex", body)


def table_indicators(ind: pd.DataFrame, win: pd.DataFrame) -> None:
    for group, members in (("rl", [OURS] + RL), ("ablation", [OURS] + ABLATION)):
        rows = []
        for ind_name in ("IGD", "Spread", "HV"):
            sub = ind[(ind.group == group) & (ind.indicator == ind_name)]
            means = {m: sub[sub.method == m]["value"].mean() for m in members}
            wins = {m: win[(win.group == group) & (win.indicator == ind_name)
                           & (win.method == m)]["win_rate"].iloc[0] for m in members}
            target = max if ind_name == "HV" else min
            bestv = target(means.values())
            cs = []
            for m in members:
                v = f"{means[m]:.3f}"
                cs.append(rf"\textbf{{{v}}}" if means[m] == bestv else v)
            rows.append(f"{ind_name} (mean) & " + " & ".join(cs) + r" \\")
            bw = max(wins.values())
            cs = []
            for m in members:
                v = f"{wins[m]:.1f}"
                cs.append(rf"\textbf{{{v}}}" if wins[m] == bw else v)
            rows.append(r"\quad win rate (\%) & " + " & ".join(cs) + r" \\")
            rows.append(r"\addlinespace")
            for m in members:
                put(f"{ind_name}Win{SLUG[m]}{group.capitalize()}", f"{wins[m]:.1f}\\%")
        head = " & ".join(TEX[m] for m in members)
        body = (r"\begin{tabular}{l" + "r" * len(members) + r"""}
\toprule
Indicator & """ + head + r""" \\
\midrule
""" + "\n".join(rows[:-1]) + r"""
\bottomrule
\multicolumn{""" + str(len(members) + 1) + r"""}{l}{\footnotesize Means over the
 27 instances. IGD and Spread are minimized, HV is maximized.} \\
\end{tabular}""")
        write(TABLES / f"indicators_{group}.tex", body)


