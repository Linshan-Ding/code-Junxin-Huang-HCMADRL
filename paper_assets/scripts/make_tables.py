def table_runtime(rt: pd.DataFrame) -> None:
    rows = []
    for m in ORDER:
        d = rt[rt.method == m]
        if d.empty:
            continue
        cs = [f"{d[d.M == M].sec_per_episode.mean():.2f}" for M in (4, 8, 12)]
        rows.append(f"{TEX[m]} & " + " & ".join(cs) +
                    f" & {d.sec_per_episode.mean():.2f} \\\\")
    body = (r"""\begin{tabular}{lrrrr}
\toprule
Method & $M=4$ & $M=8$ & $M=12$ & Mean \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\multicolumn{5}{l}{\footnotesize Wall-clock seconds per training episode,
 averaged over the nine instances} \\
\multicolumn{5}{l}{\footnotesize of each size group at $\alpha_t=\alpha_c=0.5$.} \\
\end{tabular}""")
    write(TABLES / "runtime.tex", body)
    for m in ORDER:
        d = rt[rt.method == m]
        if not d.empty:
            put(f"Sec{SLUG[m]}", f"{d.sec_per_episode.mean():.2f}")


