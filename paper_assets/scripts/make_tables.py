# Dominance counts behind the two front figures
# --------------------------------------------------------------------------
PARETO_RL_CIDS = ["C11", "C18", "C21", "C23", "C24", "C25"]
PARETO_ABL_CIDS = ["C3", "C5", "C17", "C19", "C20", "C21"]


def pareto_macros(pts: pd.DataFrame) -> None:
    """How the plotted fronts stand against ours, counted rather than eyeballed."""
    f = pts[pts.nondominated]

    def dominated(a, b):
        """Rows of b that some row of a dominates."""
        return sum(bool(np.any(np.all(a <= p, axis=1) & np.any(a < p, axis=1)))
                   for p in b)

    for tag, rivals, cids in (("Rl", RL, PARETO_RL_CIDS),
                              ("Abl", ABLATION, PARETO_ABL_CIDS)):
        beaten = total = lost = mine = 0
        for c in cids:
            ours = f[(f.cid == c) & (f.method == OURS)][["makespan", "cost"]].to_numpy()
            them = f[(f.cid == c) & (f.method.isin(rivals))][["makespan", "cost"]].to_numpy()
            total += len(them)
            mine += len(ours)
            beaten += dominated(ours, them)
            lost += dominated(them, ours)
        put(f"FrontBeaten{tag}", str(beaten))
        put(f"FrontTotal{tag}", str(total))
        put(f"FrontLost{tag}", str(lost))
        put(f"FrontOurs{tag}", str(mine))


# --------------------------------------------------------------------------
def main() -> None:
    TABLES.mkdir(exist_ok=True)
    MACROS.mkdir(exist_ok=True)
    print("tables:")
    inst = pd.read_csv(DATA / "instances.csv")
    cells = pd.read_csv(DATA / "eval_cells.csv")
    pair = pd.read_csv(DATA / "stats_pairwise.csv")
    summ = pd.read_csv(DATA / "stats_summary.csv")
    ind = pd.read_csv(DATA / "indicators.csv")
    win = pd.read_csv(DATA / "indicator_winrate.csv")
    bm = pd.read_csv(DATA / "benchmark_rmssp.csv")
    rt = pd.read_csv(DATA / "runtime.csv")
    pts = pd.read_csv(DATA / "pareto_points.csv")

    table_instances(inst)
    table_main(cells, pair)
    table_stats(pair, summ)
    table_ranks(summ)
    table_indicators(ind, win)
    table_benchmark(bm)
    table_runtime(rt)
    pareto_macros(pts)

    lines = [HEADER]
    for name in sorted(macros):
        assert re.fullmatch(r"[A-Za-z]+", name), name
        lines.append(f"\\newcommand{{\\{name}}}{{{macros[name]}\\xspace}}")
    (MACROS / "results.tex").write_text("\n".join(lines) + "\n")
    print(f"\nmacros: {len(macros)} definitions -> macros/results.tex")


if __name__ == "__main__":
    main()
