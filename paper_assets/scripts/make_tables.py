#!/usr/bin/env python3
"""Generate every results table and every inline result macro from the CSVs in
figures/data/.

Nothing in the manuscript body types an experimental number by hand: the body
either \\input's a file from tables/ or calls a macro from macros/results.tex.
Re-running this script after a change to the experiments updates both.

Usage:  python3 scripts/make_tables.py
"""
from __future__ import annotations

import re
import os
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "figures" / "data"
def paper_root() -> Path:
    """Where the manuscript lives.

    The paper repository carries only what a compile needs -- sources, class
    files, the figure PDFs -- so this toolchain lives in the code repository
    beside the raw results and writes its products across. Override with
    $HCMAGRL_PAPER; the default is the sibling checkout.
    """
    return Path(os.environ.get(
        "HCMAGRL_PAPER",
        Path(__file__).resolve().parents[3] / "Junxin_Huang_HCMAGRL_RMS_FRT"))


PAPER = paper_root()
TABLES = PAPER / "tables"
MACROS = PAPER / "macros"

OURS = "HCMAGRL"
ABLATION = ["w/o EdgeAttn", "w/o Hierarchy", "w/o Heterogeneity", "w/o Graph"]
RL = ["DDQN", "EDQN", "SAC", "D-DRL"]
ORDER = [OURS] + ABLATION + RL

# Method label -> LaTeX label used in the tables.
TEX = {
    OURS: r"\textbf{HCMAGRL}",
    "w/o EdgeAttn": r"HCMAGRL$-$A",
    "w/o Hierarchy": r"HCMAGRL$-$H",
    "w/o Heterogeneity": r"HCMAGRL$-$T",
    "w/o Graph": r"HCMAGRL$-$G",
    "DDQN": "DDQN", "EDQN": "EDQN", "SAC": "SAC", "D-DRL": "D-DRL",
}
# Macro-safe names (LaTeX control sequences may only contain letters).
SLUG = {
    OURS: "Ours", "w/o EdgeAttn": "NoAttn", "w/o Hierarchy": "NoHier",
    "w/o Heterogeneity": "NoHet", "w/o Graph": "NoGraph",
    "DDQN": "DDQN", "EDQN": "EDQN", "SAC": "SAC", "D-DRL": "DDRL",
}

HEADER = ("%% Generated by scripts/make_tables.py -- do not edit by hand.\n"
          "%% Regenerate with: python3 scripts/make_tables.py\n")

macros: dict[str, str] = {}


def put(name: str, value: str) -> None:
    macros[name] = value


def stars(p: float) -> str:
    return "$^{***}$" if p < 1e-3 else "$^{**}$" if p < 1e-2 else "$^{*}$" if p < 0.05 else ""


def fmt_p(p: float) -> str:
    return r"$<$0.001" if p < 1e-3 else f"{p:.3f}"


def write(path: Path, body: str) -> None:
    path.write_text(HEADER + body)
    print(f"  {path.relative_to(PAPER)}")


# --------------------------------------------------------------------------
def table_instances(inst: pd.DataFrame) -> None:
    rows = []
    for _, r in inst.iterrows():
        name = r.instance_id.replace("_", "\\_")
        rows.append(
            f"{r.cid} & {name} & {r.M} & {r.A} & {r.R} & "
            f"{r.J} & {r.op_types} & {r.n_jobs} & {r.n_operations} & "
            f"{r.avg_elig_machines:.2f} & {r.avg_elig_modules:.2f} & "
            f"{r.avg_reconfig_time:.1f} & {r.avg_fuzzy_spread:.1f} & "
            f"{r.avg_reconfig_cost:.1f} \\\\")
    body = (r"""\begin{tabular}{llrrrrrrrrrrrr}
\toprule
 &  & \multicolumn{4}{c}{Dimensions} & \multicolumn{3}{c}{Workload} &
 \multicolumn{2}{c}{Flexibility} & \multicolumn{3}{c}{Reconfiguration} \\
\cmidrule(lr){3-6}\cmidrule(lr){7-9}\cmidrule(lr){10-11}\cmidrule(lr){12-14}
ID & Instance & $M$ & $A$ & $R$ & $J$ & $|\mathcal{O}|$ & jobs & ops &
 cells & mod. & $\bar{t}$ & $\overline{u-\ell}$ & $\bar{c}$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}""")
    write(TABLES / "instances.tex", body)
    put("NumInstances", str(len(inst)))
    put("MinOps", str(int(inst.n_operations.min())))
    put("MaxOps", str(int(inst.n_operations.max())))
    put("MinJobs", str(int(inst.n_jobs.min())))
    put("MaxJobs", str(int(inst.n_jobs.max())))
    put("MeanFuzzySpread", f"{inst.avg_fuzzy_spread.mean():.1f}")
    put("MeanReconfigTime", f"{inst.avg_reconfig_time.mean():.1f}")


