def table_stats(pair: pd.DataFrame, summ: pd.DataFrame) -> None:
    rows = []
    for group, members in (("Ablated variants", ABLATION),
                           ("Reinforcement learning baselines", RL)):
        rows.append(rf"\multicolumn{{8}}{{l}}{{\textit{{{group}}}}} \\")
        for m in members:
            r = pair[(pair.metric == "score") & (pair.method_b == m)].iloc[0]
            rm = pair[(pair.metric == "makespan") & (pair.method_b == m)].iloc[0]
            rc = pair[(pair.metric == "cost") & (pair.method_b == m)].iloc[0]
            rows.append(
                f"\\quad {TEX[m]} & {rm.rel_gap_pct:+.2f} & {fmt_p(rm.p_value)}{stars(rm.p_value)} & "
                f"{rc.rel_gap_pct:+.2f} & {fmt_p(rc.p_value)}{stars(rc.p_value)} & "
                f"{r.rel_gap_pct:+.2f} & {fmt_p(r.p_value)}{stars(r.p_value)} & "
                f"{r.cohens_d:+.2f} \\\\")
        rows.append(r"\addlinespace")
    n = int(pair[pair.metric == "score"].n_pairs.iloc[0])
    body = (r"""\begin{tabular}{lrrrrrrr}
\toprule
 & \multicolumn{2}{c}{Makespan $C_{\max}$} & \multicolumn{2}{c}{Cost $Z$} &
 \multicolumn{3}{c}{Scalarized score} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-8}
HCMAGRL versus & $\Delta$ (\%) & $p$ & $\Delta$ (\%) & $p$ & $\Delta$ (\%) & $p$ &
 Cohen's $d$ \\
\midrule
""" + "\n".join(rows[:-1]) + r"""
\bottomrule
\multicolumn{8}{l}{\footnotesize Paired Wilcoxon signed-rank test over
 $N=""" + str(n) + r"""$ (instance, weight) settings; each is a mean over 20} \\
\multicolumn{8}{l}{\footnotesize evaluation seeds. Negative $\Delta$ favours
 HCMAGRL. $^{*}p<0.05$, $^{**}p<0.01$, $^{***}p<0.001$.} \\
\end{tabular}""")
    write(TABLES / "statistics.tex", body)

    for _, r in pair.iterrows():
        tag = {"score": "Score", "makespan": "Ms", "cost": "Cost"}[r.metric]
        put(f"Gap{tag}{SLUG[r.method_b]}", f"{abs(r.rel_gap_pct):.1f}\\%")
        put(f"P{tag}{SLUG[r.method_b]}",
            "$<$0.001" if r.p_value < 1e-3 else f"{r.p_value:.3f}")
    put("NCells", str(n))
    # Per-family Friedman/Nemenyi macros: FriedmanChiAblation, NemenyiCDAblation,
    # RankAblationOurs, ... plus the pooled nine-method family "All".
    for fam in summ["family"].unique():
        f = summ[summ.family == fam]
        tag = fam.capitalize()
        put(f"FriedmanChi{tag}", f"{f.friedman_chi2.iloc[0]:.1f}")
        put(f"NemenyiCD{tag}", f"{f.nemenyi_cd.iloc[0]:.3f}")
        put(f"KMethods{tag}", str(int(f.k_methods.iloc[0])))
        for _, r in f.iterrows():
            put(f"Rank{tag}{SLUG[r.method]}", f"{r.avg_rank:.2f}")
            if r.method != OURS:
                put(f"RankGap{tag}{SLUG[r.method]}", f"{r.gap_to_best:.2f}")
        sep = f[(f.method != OURS) & f.separated]["method"].tolist()
        put(f"NSeparated{tag}", str(len(sep)))


