def table_benchmark(bm: pd.DataFrame) -> None:
    """Instance sizes are the rows: with 12 sizes and 5 algorithms under two
    budgets, the transposed layout is the only one that fits the text width."""
    sizes = bm[bm.criterion == "evaluations"]["size"].unique().tolist()
    algos = ["SADE", "MSELS", "IGA", "DABC", OURS]
    crits = ("evaluations", "runtime")
    tab = {(c, a): bm[(bm.criterion == c) & (bm.algorithm == a)]
                     .set_index("size")["makespan"] for c in crits for a in algos}

    rows = []
    for s in sizes + ["Average"]:
        cells = []
        for c in crits:
            vals = {a: (tab[(c, a)].reindex(sizes).mean() if s == "Average"
                        else tab[(c, a)].get(s, np.nan)) for a in algos}
            best = min(vals.values())
            for a in algos:
                t = f"{vals[a]:.1f}"
                cells.append(rf"\textbf{{{t}}}" if vals[a] == best else t)
        label = s if s == "Average" else s.replace("x", r"$\times$")
        if s == "Average":
            rows.append(r"\midrule")
            label = r"\textit{Average}"
        rows.append(f"{label} & " + " & ".join(cells) + r" \\")

    head = " & ".join(TEX.get(a, a) for a in algos)
    body = (r"\begin{tabular}{l" + "r" * (2 * len(algos)) + r"""}
\toprule
 & \multicolumn{5}{c}{Termination: $m\,n\times 1000$ evaluations}
 & \multicolumn{5}{c}{Termination: $m\,n\times 8$\,s} \\
\cmidrule(lr){2-6}\cmidrule(lr){7-11}
Size $m\times n$ & """ + head + " & " + head + r""" \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\multicolumn{11}{l}{\footnotesize Makespan on the public RMSSP benchmark. The
 metaheuristic results are reported under the two termination criteria used by} \\
\multicolumn{11}{l}{\footnotesize their source; HCMAGRL is a single set of
 results compared against both. Best value per block in bold.} \\
\end{tabular}""")
    write(TABLES / "benchmark.tex", body)

    ours = bm[(bm.criterion == "evaluations") & (bm.algorithm == OURS)]["makespan"].mean()
    for a in ("DABC", "IGA", "SADE", "MSELS"):
        for crit, tag in (("evaluations", "Ev"), ("runtime", "Rt")):
            v = bm[(bm.criterion == crit) & (bm.algorithm == a)]["makespan"].mean()
            put(f"Bench{tag}{a}", f"{v:.1f}")
            # Reported as a magnitude; the direction is stated in words.
            put(f"BenchGap{tag}{a}", f"{abs(100 * (ours - v) / v):.1f}\\%")
    put("BenchOurs", f"{ours:.1f}")


