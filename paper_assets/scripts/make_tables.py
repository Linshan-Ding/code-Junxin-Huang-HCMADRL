def table_main(cells: pd.DataFrame, pair: pd.DataFrame) -> None:
    cells = cells.copy()
    cells["M"] = cells.instance_id.str.extract(r"M(\d+)_").astype(int)
    out = []
    for m in ORDER:
        d = cells[cells.method == m]
        cs = []
        for M in (4, 8, 12):
            g = d[d.M == M]
            cs += [f"{g.makespan_mean.mean():.1f}", f"{g.cost_mean.mean():.1f}"]
        cs += [f"{d.makespan_mean.mean():.1f}", f"{d.cost_mean.mean():.1f}"]
        out.append((m, cs))

    # Bold the best value in each column.
    best = []
    for c in range(8):
        vals = [float(cs[c]) for _, cs in out]
        best.append(min(vals))
    rows = []
    for m, cs in out:
        cells_tex = []
        for c, v in enumerate(cs):
            cells_tex.append(rf"\textbf{{{v}}}" if float(v) == best[c] else v)
        rows.append(f"{TEX[m]} & " + " & ".join(cells_tex) + r" \\")
    rows.insert(1, r"\addlinespace")
    rows.insert(6, r"\addlinespace")

    body = (r"""\begin{tabular}{lrrrrrrrr}
\toprule
 & \multicolumn{2}{c}{$M=4$} & \multicolumn{2}{c}{$M=8$} &
 \multicolumn{2}{c}{$M=12$} & \multicolumn{2}{c}{All instances} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}
Method & $C_{\max}$ & $Z$ & $C_{\max}$ & $Z$ & $C_{\max}$ & $Z$ & $C_{\max}$ & $Z$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}""")
    write(TABLES / "main_results.tex", body)

    for m in ORDER:
        d = cells[cells.method == m]
        put(f"Makespan{SLUG[m]}", f"{d.makespan_mean.mean():.1f}")
        put(f"Cost{SLUG[m]}", f"{d.cost_mean.mean():.1f}")


